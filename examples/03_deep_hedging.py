"""Deep hedging of a short 3M EURUSD ATM call under regime-switching Heston.

Trains two deep hedgers (forwards only; forwards + variance swap) and compares
them out of sample with classical benchmarks, on a calm-start test market and
on a stress-start market the models never trained on.

Run:  python examples/03_deep_hedging.py          (~8 min on a laptop CPU)
      python examples/03_deep_hedging.py --quick  (smoke test, writes nothing)
"""

from __future__ import annotations

import argparse
import time
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

from deltasigma.hedging import (  # noqa: E402
    CostModel,
    OptionBook,
    VanillaOption,
    black_delta,
    delta_vega,
    generate_market,
    hedge_outcome,
    no_hedge,
    summarize,
    tune_whalley_wilmott,
    whalley_wilmott,
)
from deltasigma.hedging.deep import DeepHedger, DeepHedgerConfig  # noqa: E402
from deltasigma.sim import eurusd_calm_stress_model  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
S0, T, N_STEPS = 1.085, 0.25, 63
COLUMNS = [
    ("mean", "Mean cost"),
    ("std", "Std"),
    ("cvar95_price", "CVaR95"),
    ("cvar99_price", "CVaR99"),
    ("risk_premium95", "Risk premium (CVaR95 - fair)"),
    ("cost", "Txn costs"),
    ("turnover", "Fwd turnover"),
]


def markdown_table(rows: dict[str, dict[str, float]], fair: float) -> str:
    head = "| Strategy | " + " | ".join(c[1] for c in COLUMNS) + " |"
    sep = "|---|" + "---:|" * len(COLUMNS)
    lines = [head, sep]
    for name, s in rows.items():
        cells = [f"{s[k]:.2f}" if k == "turnover" else f"{s[k]:.1f}" for k, _ in COLUMNS]
        lines.append(f"| {name} | " + " | ".join(cells) + " |")
    lines.append(f"\nFair (risk-neutral) value of the option: **{fair:.1f} pips**.")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--quick", action="store_true", help="tiny run for CI smoke tests")
    args = parser.parse_args()
    n_train, n_val, n_test, epochs = (
        (4_000, 2_000, 4_000, 2) if args.quick else (50_000, 20_000, 50_000, 30)
    )

    model = eurusd_calm_stress_model()
    F0 = S0 * np.exp((model.rd - model.rf) * T)
    book = OptionBook.of([VanillaOption(strike=F0, call=True, quantity=1.0)])
    costs = CostModel(forward_bps=2.0, varswap_vol_pts=0.2)

    def market(n: int, seed: int, regime: int = 0):
        return generate_market(model, book, S0, T, N_STEPS, n, start_regime=regime, seed=seed)

    train, val = market(n_train, 1), market(n_val, 2)
    tests = {"calm-start test": market(n_test, 3), "stress-start test": market(n_test, 4, 1)}

    gamma = tune_whalley_wilmott(train, costs)
    print(f"Whalley-Wilmott risk aversion tuned on training data: {gamma:g}")

    hedgers = {}
    for label, inst in [("Deep hedge (fwd)", ("forward",)),
                        ("Deep hedge (fwd + var swap)", ("forward", "variance_swap"))]:
        t0 = time.time()
        hedger = DeepHedger(DeepHedgerConfig(instruments=inst, epochs=epochs), costs)
        hist = hedger.fit(train, val)
        print(f"{label}: trained in {time.time() - t0:.0f}s, best epoch {hist.best_epoch}, "
              f"val CVaR95 {min(hist.val_cvar):.1f} pips")
        hedgers[label] = hedger

    def strategies(m):
        return {
            "No hedge": no_hedge(m),
            "Black delta (inception vol)": black_delta(m, "inception"),
            "Black delta (live vol)": black_delta(m),
            "Whalley-Wilmott band": whalley_wilmott(m, costs, gamma),
            "Deep hedge (fwd)": hedgers["Deep hedge (fwd)"].positions(m),
            "Delta-vega (fwd + var swap)": delta_vega(m),
            "Deep hedge (fwd + var swap)": hedgers["Deep hedge (fwd + var swap)"].positions(m),
        }

    report = ["# Deep hedging results\n",
              "Short 1 x 3M EURUSD ATM call, daily rebalancing, costs: forward 2 bp, "
              "variance swap 0.2 vol pts half-spread. All figures in **pips per EUR notional** "
              "(loss = payoff - hedge gains + costs; lower is better). Out-of-sample paths only.\n",
              f"Generated by `examples/03_deep_hedging.py` "
              f"({n_train:,} train / {n_val:,} validation / {n_test:,} test paths).\n"]
    outcomes = {}
    for name, m in tests.items():
        rows = {}
        outcomes[name] = {}
        for label, pos in strategies(m).items():
            out = hedge_outcome(m, pos, costs)
            outcomes[name][label] = out
            rows[label] = summarize(out, m.fair_price)
        table = markdown_table(rows, m.fair_price / 1e-4)
        print(f"\n## {name}\n{table}")
        report.append(f"## {name}\n\n{table}\n")

    calm = tests["calm-start test"]
    hit = calm.visited_stress()
    print(f"\n{hit.mean():.1%} of calm-start test paths enter the stress regime")

    if args.quick:
        return

    fig, axes = plt.subplots(1, 3, figsize=(17, 4.8))
    labels = ["Black delta (live vol)", "Whalley-Wilmott band", "Deep hedge (fwd)",
              "Delta-vega (fwd + var swap)", "Deep hedge (fwd + var swap)"]
    x = np.arange(len(labels))
    for i, (name, m) in enumerate(tests.items()):
        vals = [summarize(outcomes[name][lab], m.fair_price)["risk_premium95"] for lab in labels]
        axes[0].bar(x + (i - 0.5) * 0.38, vals, width=0.38, label=name)
    axes[0].set_xticks(x, [lab.replace(" (", "\n(") for lab in labels], fontsize=7)
    axes[0].set(title="Risk premium a CVaR95 desk must charge (pips)", ylabel="pips")
    axes[0].legend(fontsize=8)

    bins = np.linspace(80, 320, 120)
    for lab in ["Delta-vega (fwd + var swap)", "Deep hedge (fwd + var swap)"]:
        axes[1].hist(outcomes["calm-start test"][lab].loss / 1e-4, bins=bins, alpha=0.55,
                     density=True, label=lab)
    axes[1].axvline(calm.fair_price / 1e-4, color="k", ls=":", lw=1, label="fair value")
    axes[1].set(title="Terminal hedging cost distribution", xlabel="pips", yticks=[])
    axes[1].legend(fontsize=8)

    deviations = np.linspace(-0.25, 0.25, 201)
    step = N_STEPS // 2
    path = int(np.argmin(np.abs(np.log(calm.forward[:, step] / F0))))
    deep_trade = hedgers["Deep hedge (fwd)"].trade_response(calm, step, deviations, path)
    _, _, g_, _ = calm.book.black_greeks(calm.forward[path:path + 1, step], calm.tau[step:step + 1],
                                         calm.implied_vol[path:path + 1, step])
    half = float(np.cbrt(1.5 * costs.forward_bps * 1e-4 * calm.forward[path, step] * g_[0] ** 2
                         / gamma))
    ww_trade = np.where(np.abs(deviations) <= half, 0.0, -deviations + np.sign(deviations) * half)
    axes[2].plot(deviations, deep_trade, label="Deep hedge (learned)")
    axes[2].plot(deviations, ww_trade, "--", label="Whalley-Wilmott band")
    axes[2].plot(deviations, -deviations, ":", color="grey", label="full re-hedge to delta")
    axes[2].set(title="Learned rebalancing rule vs Whalley-Wilmott (ATM, mid-life)",
                xlabel="inherited position - Black delta", ylabel="forward trade")
    axes[2].legend(fontsize=8)

    fig.tight_layout()
    (ROOT / "docs" / "images").mkdir(parents=True, exist_ok=True)
    fig.savefig(ROOT / "docs" / "images" / "deep_hedging.png", dpi=130)
    (ROOT / "docs" / "deep_hedging_results.md").write_text("\n".join(report), encoding="utf-8")
    print("saved docs/images/deep_hedging.png and docs/deep_hedging_results.md")


if __name__ == "__main__":
    main()
